const safetyConcernPatterns = [
  /не хочу жить/i,
  /хочу умереть/i,
  /лучше бы меня не было/i,
  /покончить с собой/i,
  /убить себя/i,
  /причинить себе вред/i,
  /навредить себе/i,
  /суицид/i,
  /самоубийств/i,
  /меня хотят убить/i,
  /мне угрожают/i,
  /мне небезопасно/i,
  /меня избивают/i,
  /меня бьют/i
];

export function detectSafetyConcern(text) {
  if (typeof text !== "string") {
    return false;
  }

  const normalizedText = text.trim();

  if (!normalizedText) {
    return false;
  }

  return safetyConcernPatterns.some((pattern) =>
    pattern.test(normalizedText)
  );
}

