const immediateRiskPatterns = [
  /хочу умереть/i,
  /хочу покончить с собой/i,
  /хочу убить себя/i,
  /убью себя/i,
  /покончу с собой/i,
  /не хочу жить/i
];

export function detectImmediateRisk(
  text
) {
  return immediateRiskPatterns.some(
    (pattern) =>
      pattern.test(text)
  );
}

